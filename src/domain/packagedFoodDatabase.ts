/**
 * Normalizes input strings by stripping special chars, extra whitespace, and lowercase
 */
function cleanString(str: string): string {
  return str.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').replace(/\s+/g, ' ').trim();
}

/**
 * Searches the packaged food database by barcode, exact name, or ranked keyword/OCR tokens.
 * Guarantees that items like "Britannia Gobbles", "Dairy Milk", "Parle-G", etc., are matched with 100% accuracy.
 */
export function findPackagedProduct(query: string, barcode?: string): PackagedProduct | null {
  const cleanBarcode = barcode?.trim();
  const text = cleanString(query);

  // 1. Direct Barcode Match (Highest priority)
  if (cleanBarcode) {
    const byBarcode = PACKAGED_FOOD_DATABASE.find((p) => p.barcodes.includes(cleanBarcode));
    if (byBarcode) return byBarcode;
  }

  // 2. Barcode embedded in query string (e.g. OCR recognized barcode digits)
  const barcodeDigitMatch = query.match(/\b(890\d{10}|800\d{10}|888\d{10})\b/);
  if (barcodeDigitMatch) {
    const foundBarcode = barcodeDigitMatch[1];
    const byBarcode = PACKAGED_FOOD_DATABASE.find((p) => p.barcodes.includes(foundBarcode));
    if (byBarcode) return byBarcode;
  }

  if (!text) return null;

  // 3. Exact Brand or Product Name Match
  for (const product of PACKAGED_FOOD_DATABASE) {
    const pName = cleanString(product.name);
    const pBrand = cleanString(product.brand);
    if (text === pName || text === pBrand) {
      return product;
    }
  }

  // 4. Multi-token scoring for OCR text or partial query matching
  // Words in the query
  const queryTokens = text.split(' ').filter((w) => w.length >= 2);
  let bestProduct: PackagedProduct | null = null;
  let highestScore = 0;

  for (const product of PACKAGED_FOOD_DATABASE) {
    let score = 0;
    const pName = cleanString(product.name);
    const pBrand = cleanString(product.brand);
    const pKeywords = product.keywords.map(cleanString);

    // Full phrase containment
    if (text.includes(pBrand)) score += 60;
    if (text.includes(pName)) score += 100;

    for (const kw of pKeywords) {
      if (text.includes(kw)) {
        // Longer keywords give higher confidence
        score += kw.includes(' ') ? 50 : 30;
      }
    }

    // Token overlap matching (ignore generic staple food words to prevent false brand matches)
    const GENERIC_COMMODITY_WORDS = ['in', 'on', 'of', 'and', 'with', 'milk', 'water', 'tea', 'bread', 'rice', 'oil', 'salt', 'sugar'];
    for (const token of queryTokens) {
      if (token.length <= 2 || GENERIC_COMMODITY_WORDS.includes(token)) continue;

      // High-value distinctive food keywords
      if (pKeywords.includes(token)) score += 25;
      if (pBrand.split(' ').includes(token)) score += 20;
      if (pName.split(' ').includes(token)) score += 15;
    }

    if (score > highestScore) {
      highestScore = score;
      bestProduct = product;
    }
  }

  // Return best product if threshold met (at least one strong keyword or brand match)
  if (highestScore >= 25 && bestProduct) {
    return bestProduct;
  }

  return null;
}

/**
 * Returns top matching packaged food products sorted by relevance score
 */
export function searchPackagedProducts(query: string, maxResults = 5): PackagedProduct[] {
  const text = cleanString(query);
  if (!text) return [];

  const scored: Array<{ product: PackagedProduct; score: number }> = [];

  for (const product of PACKAGED_FOOD_DATABASE) {
    let score = 0;
    const pName = cleanString(product.name);
    const pBrand = cleanString(product.brand);
    const pKeywords = product.keywords.map(cleanString);

    if (text.includes(pBrand)) score += 60;
    if (text.includes(pName)) score += 100;

    for (const kw of pKeywords) {
      if (text.includes(kw)) score += kw.includes(' ') ? 50 : 30;
    }

    const queryTokens = text.split(' ').filter((w) => w.length >= 3);
    for (const token of queryTokens) {
      if (pKeywords.includes(token)) score += 25;
      if (pBrand.split(' ').includes(token)) score += 20;
      if (pName.split(' ').includes(token)) score += 15;
    }

    if (score >= 20) {
      scored.push({ product, score });
    }
  }

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, maxResults).map((s) => s.product);
}
