/**
 * Searches the packaged food database by barcode, exact name, or partial keyword tokens
 */
export function findPackagedProduct(query: string, barcode?: string): PackagedProduct | null {
  const cleanBarcode = barcode?.trim();
  const cleanText = query.trim().toLowerCase();

  // 1. Direct barcode match
  if (cleanBarcode) {
    const byBarcode = PACKAGED_FOOD_DATABASE.find((p) => p.barcodes.includes(cleanBarcode));
    if (byBarcode) return byBarcode;
  }

  // 2. Keyword token matching
  for (const product of PACKAGED_FOOD_DATABASE) {
    for (const kw of product.keywords) {
      // Exact match or multi-word keyword containment
      if (cleanText === kw) {
        return product;
      }
      if (kw.includes(' ') && cleanText.includes(kw)) {
        return product;
      }
      if (cleanText.includes(' ') && kw.includes(cleanText)) {
        return product;
      }
    }
  }

  // 3. Brand or Product Name match
  for (const product of PACKAGED_FOOD_DATABASE) {
    const brandLower = product.brand.toLowerCase();
    const nameLower = product.name.toLowerCase();
    if (cleanText === brandLower || cleanText === nameLower) {
      return product;
    }
    if (brandLower.length > 3 && cleanText.includes(brandLower)) {
      return product;
    }
    if (cleanText.includes(nameLower)) {
      return product;
    }
  }

  return null;
}
